def test_verify_checksum_mismatch_rejected():
    print("checksum mismatch rejected")
    seed()
    bdir = _cleanup_backup_dir()
    good = backup.create_backup()["filename"]
    zp = bdir / good
    tmp = Path(tempfile.mkdtemp())
    with zipfile.ZipFile(str(zp)) as zf:
        zf.extractall(str(tmp))
    mf = tmp / "manifest.json"
    m = json.loads(mf.read_text())
    m["files"]["teamhr.db"] = "0" * 64
    mf.write_text(json.dumps(m))
    tampered = bdir / "TeamHR_Backup_TAMPERED.zip"
    with zipfile.ZipFile(str(tampered), "w") as zf:
        zf.write(mf, "manifest.json")
        zf.write(tmp / "teamhr.db", "teamhr.db")
    v = backup.verify_backup(tampered)
    check("invalid", v.get("valid") is False)
    check("contains checksum", "checksum" in (v.get("error") or "").lower())



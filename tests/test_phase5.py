def test_restore_pre_restore_backup_created():
    print("restore creates pre-restore backup + reverts DB")
    seed()
    bdir = _cleanup_backup_dir()
    good = backup.create_backup()["filename"]
    # Now mutate the live DB (extra candidate) AFTER the good backup.
    db.insert_candidate({"name": "EXTRA", "mobile": "9000000999",
                         "status": "ready", "batch_id": 1})
    check("live has 2 before restore", len(db.list_candidates()) == 2)
    rr = backup.restore_backup(good)
    check("restore ok", rr.get("ok") is True)
    check("pre-restore recorded", bool(rr.get("pre_restore")))
    check("pre-restore file exists", (bdir / rr["pre_restore"]).exists())
    check("pre-restore distinct from source", rr["pre_restore"] != good)
    check("candidates back to 1", len(db.list_candidates()) == 1)

    # The pre-restore backup must contain the 2-candidate (post-mutation) DB,
    # proving it snapshot the current state before the swap.
    tmp = Path(tempfile.mkdtemp())
    with zipfile.ZipFile(str(bdir / rr["pre_restore"])) as zf:
        zf.extract("teamhr.db", str(tmp))
    conn = sqlite3.connect(str(tmp / "teamhr.db"))
    try:
        pre_count = conn.execute("SELECT COUNT(*) FROM candidates").fetchone()[0]
    finally:
        conn.close()
    check("pre-restore db captured 2 candidates", pre_count == 2)

    # Restore Completed is recorded into the restored DB after the swap.
    events = [e["event_type"] for e in db.list_system_events()]
    check("audit event Restore Completed", "Restore Completed" in events)



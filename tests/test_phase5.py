def test_draft_create_update_resume_discard():
    print("candidate_drafts create/update/resume/discard")
    client = seed()
    r = client.post("/api/drafts", json={
        "draft_type": "manual_entry",
        "safe_payload": {"candidate_name": "Draft One", "mobile": "9000000007"},
    })
    check("created", r.status_code == 200 and r.json().get("ok"))
    did = r.json()["draft_id"]
    r = client.post("/api/drafts", json={
        "draft_type": "manual_entry", "draft_id": did,
        "safe_payload": {"candidate_name": "Draft One Updated", "mobile": "9000000008"},
    })
    check("updated ok", r.status_code == 200 and r.json().get("ok"))
    res = client.get("/api/drafts?draft_type=manual_entry").json()
    check("resume lists draft", len(res["drafts"]) == 1)
    r = client.post("/api/drafts/discard", json={"draft_id": did})
    check("discarded", r.json().get("ok") is True)
    res = client.get("/api/drafts?draft_type=manual_entry").json()
    check("draft gone", len(res["drafts"]) == 0)



def test_backup_manifest_and_checksums():
    print("backup manifest present with SHA-256 checksums")
    seed()
    bdir = _cleanup_backup_dir()
    r = backup.create_backup()
    with zipfile.ZipFile(str(bdir / r["filename"])) as zf:
        names = zf.namelist()
        manifest = json.loads(zf.read("manifest.json").decode("utf-8"))
    check("manifest present", "manifest.json" in names)
    check("db present", "teamhr.db" in names)
    check("backup_version == 1", manifest["backup_version"] == 1)
    check("created_at present", bool(manifest.get("created_at")))
    check("files checksums", "teamhr.db" in manifest["files"])
    check("two entries", len(names) == 2)

    # Verify the checksum actually matches the extracted file.
    tmp = Path(tempfile.mkdtemp())
    with zipfile.ZipFile(str(bdir / r["filename"])) as zf:
        zf.extract("teamhr.db", str(tmp))
    with open(tmp / "teamhr.db", "rb") as fh:
        import hashlib
        sha = hashlib.sha256(fh.read()).hexdigest()
    check("sha256 matches manifest", sha == manifest["files"]["teamhr.db"])


def test_db_integrity_in_backup():
    print("backed-up database passes integrity_check")
    seed()
    bdir = _cleanup_backup_dir()
    r = backup.create_backup()
    tmp = Path(tempfile.mkdtemp())
    with zipfile.ZipFile(str(bdir / r["filename"])) as zf:
        zf.extract("teamhr.db", str(tmp))
    conn = sqlite3.connect(str(tmp / "teamhr.db"))
    try:
        res = conn.execute("PRAGMA integrity_check").fetchone()[0]
    finally:
        conn.close()
    check("integrity ok", res == "ok")


